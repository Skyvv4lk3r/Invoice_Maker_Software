from dataclasses import dataclass, field
from typing import Protocol

from invoice_generator.application.contracts.workspace import (
    AuditEntry,
    CustomerRecord,
    FirmProfile,
    ItemRecord,
    TemplateVersion,
)


@dataclass(frozen=True)
class OwnerCredentials:
    username: str
    password_hash: str = field(repr=False)
    recovery_hash: str = field(repr=False)
    epoch: int = 1
    failures: int = 0
    locked_until: float = 0


class IIdentityStore(Protocol):
    def get_owner(self) -> OwnerCredentials | None: ...
    def create_owner(self, owner: OwnerCredentials, firm: FirmProfile) -> None: ...
    def record_attempt(self, expected_epoch: int, success: bool, now: float) -> None: ...
    def replace_credentials(
        self, expected_epoch: int, password_hash: str, recovery_hash: str
    ) -> None: ...


class IPasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, encoded: str, password: str) -> bool: ...


class IFirmStore(Protocol):
    def get(self) -> FirmProfile: ...
    def save(self, profile: FirmProfile) -> FirmProfile: ...
    def audit(self) -> tuple[AuditEntry, ...]: ...


class ITemplateStore(Protocol):
    def list(self) -> tuple[TemplateVersion, ...]: ...
    def get(self, template_id: str, version: int | None = None) -> TemplateVersion: ...
    def save(self, template: TemplateVersion, expected_version: int) -> TemplateVersion: ...


class IImageNormalizer(Protocol):
    def normalize(self, content: bytes) -> str: ...


class ICustomerStore(Protocol):
    def list(self) -> tuple[CustomerRecord, ...]: ...
    def save(self, record: CustomerRecord) -> CustomerRecord: ...
    def delete(self, record_id: str, revision: int) -> None: ...


class IItemStore(Protocol):
    def list(self) -> tuple[ItemRecord, ...]: ...
    def save(self, record: ItemRecord) -> ItemRecord: ...
    def delete(self, record_id: str, revision: int) -> None: ...
